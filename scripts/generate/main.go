// Command generate owns the guide topic table, CLI reference and command
// output examples. Check mode compares in memory and never rewrites the working tree.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/craigsmitham/dotspec/internal/cli"
	"github.com/craigsmitham/dotspec/internal/guide"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

func main() {
	check := flag.Bool("check", false, "verify generated files without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	var reference strings.Builder
	reference.WriteString("# CLI reference\n\nRun project commands in the directory containing your specifications. Substitute your own names, paths and project selectors in the examples. Handbook reading commands work from any directory.\n\n")
	writeCommand(&reference, cli.NewRoot())
	gallery, err := outputGallery()
	if err != nil {
		return err
	}
	guideMap, err := documentationMap()
	if err != nil {
		return err
	}
	appSpecs, err := embeddedAppSpecs()
	if err != nil {
		return err
	}
	files := []struct{ path, content string }{
		{"examples/app_specs_gen.go", appSpecs},
		{"docs/cli-handbook/README.md", guideMap},
		{"docs/reference/cli.md", reference.String()},
		{"docs/reference/command-examples.md", gallery},
	}
	var stale []string
	for _, file := range files {
		path := filepath.Join(root, file.path)
		if check {
			actual, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(actual, []byte(file.content)) {
				stale = append(stale, file.path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(file.content), 0o644); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("generated files are stale: %s; run mise run generate", strings.Join(stale, ", "))
	}
	return nil
}

// Go embed cannot cross the standalone To-do application's module boundary.
func embeddedAppSpecs() (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by scripts/generate from examples/todo/app. DO NOT EDIT.\npackage examples\n\nvar AppSpecs = map[string]string{\n")
	err := filepath.WalkDir("examples/todo/app", func(file string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.Type().IsRegular() || !strings.HasSuffix(file, ".spec.md") {
			return nil
		}
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "%q: %q,\n", strings.TrimPrefix(filepath.ToSlash(file), "examples/"), data)
		return nil
	})
	if err != nil {
		return "", err
	}
	out.WriteString("}\n")
	data, err := format.Source([]byte(out.String()))
	return string(data), err
}

// Preserve the authored navigation above the generated table.
func documentationMap() (string, error) {
	body, err := os.ReadFile("docs/cli-handbook/README.md")
	if err != nil {
		return "", err
	}
	const marker = "<!-- Generated topic navigation -->"
	intro, _, ok := strings.Cut(string(body), marker)
	if !ok {
		return "", fmt.Errorf("docs/cli-handbook/README.md is missing %s", marker)
	}
	var out strings.Builder
	out.WriteString(intro + marker + "\n")
	for _, topic := range guide.Topics() {
		fmt.Fprintf(&out, "\n### %s\n\n%s Run `dotspec docs %s`.\n\n", topic.Title, topic.Description, topic.Name)
		for _, destination := range topic.Pages {
			target, err := filepath.Rel("docs/cli-handbook", destination.Page)
			if err != nil {
				return "", err
			}
			title, err := destination.PageTitle()
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&out, "- [%s](%s) (%s)\n", title, filepath.ToSlash(target), destination.Form())
		}
	}
	return out.String(), nil
}

func writeCommand(out *strings.Builder, cmd *cobra.Command) {
	if cmd.Hidden {
		return
	}
	cmd.InitDefaultHelpFlag()
	fmt.Fprintf(out, "## %s\n\n%s\n\n```sh\n%s\n```\n", cmd.CommandPath(), cmd.Short, cmd.UseLine())
	if cmd.Long != "" {
		fmt.Fprintf(out, "\n%s\n", strings.TrimPrefix(cmd.Long, cmd.Short+"\n\n"))
	}
	if cmd.Example != "" {
		fmt.Fprintf(out, "\n```sh\n%s\n```\n", cmd.Example)
	}
	if cmd.HasAvailableFlags() {
		out.WriteString("\n| Flag | Default | Description |\n| --- | --- | --- |\n")
		cmd.Flags().VisitAll(func(f *pflag.Flag) {
			if f.Hidden {
				return
			}
			name := "--" + f.Name
			if f.Shorthand != "" {
				name += ", -" + f.Shorthand
			}
			fmt.Fprintf(out, "| `%s` | `%s` | %s |\n", name, escape(f.DefValue), escape(f.Usage))
		})
	}
	out.WriteByte('\n')
	for _, child := range cmd.Commands() {
		writeCommand(out, child)
	}
}

func escape(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s) }

func outputGallery() (result string, err error) {
	original, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir, err := os.MkdirTemp("", "dotspec-examples-")
	if err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(dir)) }()
	if err := os.Chdir(dir); err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.Chdir(original)) }()
	// Inventory examples exercise Git discovery as well as bounded context lookup.
	if output, err := exec.Command("git", "init", "--quiet", "--template=", ".").CombinedOutput(); err != nil {
		return "", fmt.Errorf("initialize example repository: %w: %s", err, output)
	}
	var gallery strings.Builder
	gallery.WriteString("# Command output examples\n\nThese commands run in order in a new Git repository. The init commands create the specifications used by later commands. `$PROJECT` stands for that directory’s absolute path.\n\n")
	for _, args := range [][]string{
		{"system", "init"}, {"job", "init", "develop-requirements"},
		{"system", "show"}, {"job", "show", "develop-requirements"},
		{"job", "outcome", "list", "develop-requirements", "--json"},
		{"job", "map", "develop-requirements", "--format", "mermaid"},
		{"job", "check", "develop-requirements", "--json"},
		{"use-case", "init", "check-specifications"},
		{"use-case", "show", "check-specifications", "--json"},
		{"use-case", "init", "review-change", "--template", "expanded"},
		{"use-case", "list", "--overview"},
		{"use-case", "check", "check-specifications", "--json"},
		{"concept", "init", "job-map"},
		{"concept", "show", "job-map", "--json"},
		{"concept", "check", "job-map", "--json"},
		{"requirement", "init", "diagnostic-severity", "--preset", "quality"},
		{"requirement", "show", "diagnostic-severity", "--json"},
		{"requirement", "check", "diagnostic-severity", "--json"},
		{"requirement", "init", "reject-existing-target"},
		{"requirement", "show", "reject-existing-target", "--json"},
		{"requirement", "list", "--json"},
		{"requirement", "check", "reject-existing-target", "--json"},
		{"sources", "--json"},
	} {
		var out, errOut bytes.Buffer
		if code := cli.Run(args, &out, &errOut); code != 0 {
			return "", fmt.Errorf("example %v failed (%d): %s %s", args, code, &out, &errOut)
		}
		resolved, err := filepath.EvalSymlinks(dir)
		if err != nil {
			return "", err
		}
		content := galleryOutput(out.String(), resolved)
		fmt.Fprintf(&gallery, "## %s\n\n```sh\ndotspec %s\n```\n\n````text\n%s````\n\n", strings.Join(args, " "), strings.Join(args, " "), content)
	}
	return gallery.String(), nil
}

var jsonString = regexp.MustCompile(`"(?:[^"\\]|\\.)*"`)

// Normalize complete JSON path strings without changing key order or escapes
// in authored Markdown. Replacing backslashes across the entire JSON output
// would corrupt its contents. The CLI retains native paths on each platform.
func galleryOutput(content, project string) string {
	if json.Valid([]byte(content)) {
		return jsonString.ReplaceAllStringFunc(content, func(token string) string {
			var value string
			if err := json.Unmarshal([]byte(token), &value); err != nil {
				return token
			}
			switch {
			case value == project:
				value = "$PROJECT"
			case strings.HasPrefix(value, project+"\\"):
				value = "$PROJECT" + strings.ReplaceAll(value[len(project):], "\\", "/")
			case strings.HasPrefix(value, project+"/"):
				value = "$PROJECT" + value[len(project):]
			default:
				return token
			}
			// Marshaling a string cannot fail.
			encoded, _ := json.Marshal(value)
			return string(encoded)
		})
	}
	return strings.ReplaceAll(content, filepath.ToSlash(project), "$PROJECT")
}
