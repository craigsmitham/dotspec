func main() {
	check := flag.Bool("check", false, "verify generated files without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	var reference strings.Builder
	reference.WriteString("# CLI reference\n\nGenerated by `go run ./scripts/generate`. Edit command definitions in `internal/cli`.\n\n")
	writeCommand(&reference, cli.NewRoot())
	gallery, err := outputGallery()
	if err != nil {
		return err
	}
	files := []struct{ path, content string }{
		{"docs/cli.md", reference.String()},
		{"examples/starter/specs/quality-models/organization-quality.quality-model.spec.md", qualitymodel.Template},
		{"examples/starter/specs/business-rules/purchase-approval.business-rule.spec.md", businessrule.Template},
		{"examples/starter/specs/system.spec.md", system.Template},
		{"examples/starter/specs/jobs/develop-requirements.job.spec.md", job.Template},
		{"examples/starter/specs/use-cases/check-specifications.use-case.spec.md", usecase.Template},
		{"examples/starter/specs/use-cases/review-change.use-case.spec.md", usecase.ExpandedTemplate},
		{"examples/starter/specs/concepts/job-map.concept.spec.md", concept.Template},
		{"examples/starter/specs/quality/diagnostic-severity.quality.spec.md", quality.Template},
		{"examples/starter/specs/requirements/reject-existing-target.requirement.spec.md", requirement.Template},
		{"docs/examples.md", gallery},
	}
	starters, err := qualitymodel.Builtins()
	if err != nil {
		return err
	}
	for _, starter := range starters {
		files = append(files, struct{ path, content string }{"docs/reference/quality-models/" + starter.Slug + ".md", "<!-- Generated by scripts/generate from the bundled quality-model source. -->\n\n" + starter.Markdown + "\n"})
	}
	result, err := model.Export(filepath.Join(root, "examples/concept-design"), system.CheckType(), concept.CheckType())
	if err != nil {
		return err
	}
	if result.ExitCode != 0 {
		return fmt.Errorf("concept example has authoring findings: %d", result.ExitCode)
	}
	findings, err := model.Validate(result.Snapshot)
	if err != nil {
		return err
	}
	if len(findings) > 0 {
		return fmt.Errorf("concept example model: %v", findings)
	}
	design, err := model.DesignMarkdown(result.Snapshot, filepath.Join(root, "docs/reference"))
	if err != nil {
		return err
	}
	files = append(files, struct{ path, content string }{"docs/reference/concept-design-example.md", design})
	traceResult, err := model.Export(filepath.Join(root, "examples/requirements-traceability"), system.CheckType(), concept.CheckType(), job.CheckType(), usecase.CheckType(), businessrule.CheckType(), requirement.CheckType(), quality.CheckType())
	if err != nil {
		return err
	}
	if traceResult.ExitCode != 0 {
		return fmt.Errorf("traceability example has authoring findings: %v", traceResult.Snapshot.Diagnostics)
	}
	traceFindings, err := model.Validate(traceResult.Snapshot)
	if err != nil {
		return err
	}
	if len(traceFindings) > 0 {
		return fmt.Errorf("traceability example model: %v", traceFindings)
	}
	trace, err := model.TraceMarkdown(traceResult.Snapshot, filepath.Join(root, "docs/reference"))
	if err != nil {
		return err
	}
	files = append(files, struct{ path, content string }{"docs/reference/requirements-traceability-example.md", trace})
	overviewResult, err := model.Export(filepath.Join(root, "examples/system-structure"), system.CheckType(), concept.CheckType(), job.CheckType(), usecase.CheckType(), businessrule.CheckType(), requirement.CheckType(), quality.CheckType())
	if err != nil {
		return err
	}
	if overviewResult.ExitCode != 0 {
		return fmt.Errorf("system structure example has authoring findings: %v", overviewResult.Snapshot.Diagnostics)
	}
	overviewFindings, err := model.Validate(overviewResult.Snapshot)
	if err != nil {
		return err
	}
	if len(overviewFindings) > 0 {
		return fmt.Errorf("system structure example model: %v", overviewFindings)
	}
	overview, err := model.OverviewMarkdown(overviewResult.Snapshot, filepath.Join(root, "docs/reference"))
	if err != nil {
		return err
	}
	files = append(files, struct{ path, content string }{"docs/reference/system-overview-example.md", overview})
	var stale []string
	for _, file := range files {
		path := filepath.Join(root, file.path)
		if check {
			actual, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(actual, []byte(file.content)) {
				stale = append(stale, file.path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(file.content), 0o644); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("generated files are stale: %s; run mise run generate", strings.Join(stale, ", "))
	}
	return nil
}

func writeCommand(out *strings.Builder, cmd *cobra.Command) {
	if cmd.Hidden {
		return
	}
	cmd.InitDefaultHelpFlag()
	fmt.Fprintf(out, "## %s\n\n%s\n\n```sh\n%s\n```\n", cmd.CommandPath(), cmd.Short, cmd.UseLine())
	if cmd.Long != "" {
		fmt.Fprintf(out, "\n%s\n", cmd.Long)
	}
	if cmd.Example != "" {
		fmt.Fprintf(out, "\n```sh\n%s\n```\n", cmd.Example)
	}
	if cmd.HasAvailableFlags() {
		out.WriteString("\n| Flag | Default | Description |\n| --- | --- | --- |\n")
		cmd.Flags().VisitAll(func(f *pflag.Flag) {
			if f.Hidden {
				return
			}
			name := "--" + f.Name
			if f.Shorthand != "" {
				name += ", -" + f.Shorthand
			}
			fmt.Fprintf(out, "| `%s` | `%s` | %s |\n", name, escape(f.DefValue), escape(f.Usage))
		})
	}
	out.WriteByte('\n')
	for _, child := range cmd.Commands() {
		writeCommand(out, child)
	}
}

func escape(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s) }

func outputGallery() (result string, err error) {
	original, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir, err := os.MkdirTemp("", "dotspec-examples-")
	if err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(dir)) }()
	if err := os.Chdir(dir); err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.Chdir(original)) }()
	// Inventory examples exercise Git discovery as well as bounded context lookup.
	if output, err := exec.Command("git", "init", "--quiet", "--template=", ".").CombinedOutput(); err != nil {
		return "", fmt.Errorf("initialize example repository: %w: %s", err, output)
	}
	var gallery strings.Builder
	gallery.WriteString("# Command examples\n\nGenerated from the CLI and its starter templates. `$PROJECT` stands for the absolute project directory.\n\n")
	for _, args := range [][]string{
		{"system", "init"}, {"job", "init", "develop-requirements"},
		{"system", "show"}, {"job", "show", "develop-requirements"},
		{"job", "step", "list", "develop-requirements"},
		{"job", "outcome", "list", "develop-requirements", "--json"},
		{"job", "map", "develop-requirements", "--format", "mermaid"},
		{"job", "check", "develop-requirements", "--json"},
		{"use-case", "init", "check-specifications"},
		{"use-case", "show", "check-specifications", "--json"},
		{"use-case", "init", "review-change", "--template", "expanded"},
		{"use-case", "list", "--overview"},
		{"use-case", "check", "check-specifications", "--json"},
		{"concept", "init", "job-map"},
		{"concept", "show", "job-map", "--json"},
		{"concept", "check", "job-map", "--json"},
		{"quality", "init", "diagnostic-severity"},
		{"quality", "show", "diagnostic-severity", "--json"},
		{"quality", "check", "diagnostic-severity", "--json"},
		{"requirement", "init", "reject-existing-target"},
		{"requirement", "show", "reject-existing-target", "--json"},
		{"requirement", "list", "--json"},
		{"requirement", "check", "reject-existing-target", "--json"},
		{"sources", "--json"},
	} {
		var out, errOut bytes.Buffer
		if code := cli.Run(args, &out, &errOut); code != 0 {
			return "", fmt.Errorf("example %v failed (%d): %s %s", args, code, &out, &errOut)
		}
		resolved, err := filepath.EvalSymlinks(dir)
		if err != nil {
			return "", err
		}
		content := galleryOutput(out.String(), resolved)
		fmt.Fprintf(&gallery, "## %s\n\n```sh\ndotspec %s\n```\n\n````text\n%s````\n\n", strings.Join(args, " "), strings.Join(args, " "), content)
	}
	return gallery.String(), nil
}

var jsonString = regexp.MustCompile(`"(?:[^"\\]|\\.)*"`)

// Normalize complete JSON path strings without changing key order or escapes
// in authored Markdown. Replacing backslashes across the entire JSON output
// would corrupt its contents. The CLI retains native paths on each platform.
func galleryOutput(content, project string) string {
	if json.Valid([]byte(content)) {
		return jsonString.ReplaceAllStringFunc(content, func(token string) string {
			var value string
			if err := json.Unmarshal([]byte(token), &value); err != nil {
				return token
			}
			switch {
			case value == project:
				value = "$PROJECT"
			case strings.HasPrefix(value, project+"\\"):
				value = "$PROJECT" + strings.ReplaceAll(value[len(project):], "\\", "/")
			case strings.HasPrefix(value, project+"/"):
				value = "$PROJECT" + value[len(project):]
			default:
				return token
			}
			// Marshaling a string cannot fail.
			encoded, _ := json.Marshal(value)
			return string(encoded)
		})
	}
	return strings.ReplaceAll(content, filepath.ToSlash(project), "$PROJECT")
}
