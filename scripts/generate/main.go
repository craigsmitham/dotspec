// Command generate owns the CLI reference, starter specifications, and output
// gallery. Check mode compares in memory and never rewrites the working tree.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/craigsmitham/dotspec/internal/cli"
	"github.com/craigsmitham/dotspec/internal/concept"
	"github.com/craigsmitham/dotspec/internal/job"
	"github.com/craigsmitham/dotspec/internal/quality"
	"github.com/craigsmitham/dotspec/internal/system"
	"github.com/craigsmitham/dotspec/internal/usecase"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

func main() {
	check := flag.Bool("check", false, "verify generated files without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	var reference strings.Builder
	reference.WriteString("# CLI reference\n\nGenerated by `go run ./scripts/generate`. Edit command definitions in `internal/cli`.\n\n")
	writeCommand(&reference, cli.NewRoot())
	gallery, err := outputGallery()
	if err != nil {
		return err
	}
	files := []struct{ path, content string }{
		{"docs/cli.md", reference.String()},
		{"examples/starter/specs/system.spec.md", system.Template},
		{"examples/starter/specs/jobs/develop-requirements.job.spec.md", job.Template},
		{"examples/starter/specs/use-cases/check-specifications.use-case.spec.md", usecase.Template},
		{"examples/starter/specs/concepts/job-map.concept.spec.md", concept.Template},
		{"examples/starter/specs/quality/diagnostic-severity.quality.spec.md", quality.Template},
		{"docs/examples.md", gallery},
	}
	var stale []string
	for _, file := range files {
		path := filepath.Join(root, file.path)
		if check {
			actual, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(actual, []byte(file.content)) {
				stale = append(stale, file.path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(file.content), 0o644); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("generated files are stale: %s; run mise run generate", strings.Join(stale, ", "))
	}
	return nil
}

func writeCommand(out *strings.Builder, cmd *cobra.Command) {
	if cmd.Hidden {
		return
	}
	cmd.InitDefaultHelpFlag()
	fmt.Fprintf(out, "## %s\n\n%s\n\n```sh\n%s\n```\n", cmd.CommandPath(), cmd.Short, cmd.UseLine())
	if cmd.Long != "" {
		fmt.Fprintf(out, "\n%s\n", cmd.Long)
	}
	if cmd.Example != "" {
		fmt.Fprintf(out, "\n```sh\n%s\n```\n", cmd.Example)
	}
	if cmd.HasAvailableFlags() {
		out.WriteString("\n| Flag | Default | Description |\n| --- | --- | --- |\n")
		cmd.Flags().VisitAll(func(f *pflag.Flag) {
			if f.Hidden {
				return
			}
			name := "--" + f.Name
			if f.Shorthand != "" {
				name += ", -" + f.Shorthand
			}
			fmt.Fprintf(out, "| `%s` | `%s` | %s |\n", name, escape(f.DefValue), escape(f.Usage))
		})
	}
	out.WriteByte('\n')
	for _, child := range cmd.Commands() {
		writeCommand(out, child)
	}
}

func escape(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s) }

func outputGallery() (result string, err error) {
	original, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir, err := os.MkdirTemp("", "dotspec-examples-")
	if err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(dir)) }()
	if err := os.Chdir(dir); err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.Chdir(original)) }()
	// Bound ancestor lookup without requiring a Git installation.
	if err := os.Mkdir(".git", 0o755); err != nil {
		return "", err
	}
	var gallery strings.Builder
	gallery.WriteString("# Command examples\n\nGenerated from the CLI and its starter templates. `$PROJECT` stands for the absolute project directory.\n\n")
	for _, args := range [][]string{
		{"system", "init"}, {"job", "init", "develop-requirements"},
		{"system", "show"}, {"job", "show", "develop-requirements"},
		{"job", "step", "list", "develop-requirements"},
		{"job", "outcome", "list", "develop-requirements", "--json"},
		{"job", "map", "develop-requirements", "--format", "mermaid"},
		{"job", "check", "develop-requirements", "--json"},
		{"use-case", "init", "check-specifications"},
		{"use-case", "show", "check-specifications", "--json"},
		{"use-case", "check", "check-specifications", "--json"},
		{"concept", "init", "job-map"},
		{"concept", "show", "job-map", "--json"},
		{"concept", "check", "job-map", "--json"},
		{"quality", "init", "diagnostic-severity"},
		{"quality", "show", "diagnostic-severity", "--json"},
		{"quality", "check", "diagnostic-severity", "--json"},
	} {
		var out, errOut bytes.Buffer
		if code := cli.Run(args, &out, &errOut); code != 0 {
			return "", fmt.Errorf("example %v failed (%d): %s %s", args, code, &out, &errOut)
		}
		resolved, err := filepath.EvalSymlinks(dir)
		if err != nil {
			return "", err
		}
		encoded, err := json.Marshal(resolved)
		if err != nil {
			return "", err
		}
		content := strings.ReplaceAll(out.String(), string(encoded[1:len(encoded)-1]), "$PROJECT")
		content = strings.ReplaceAll(content, filepath.ToSlash(resolved), "$PROJECT")
		fmt.Fprintf(&gallery, "## %s\n\n```sh\ndotspec %s\n```\n\n````text\n%s````\n\n", strings.Join(args, " "), strings.Join(args, " "), content)
	}
	return gallery.String(), nil
}
